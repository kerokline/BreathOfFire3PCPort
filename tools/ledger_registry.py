#!/usr/bin/env python
"""The ledger's switch fields as a C++ table, and the four presets read from them.

    python tools/ledger_registry.py                 # write src/launcher/ledger_registry.h
    python tools/ledger_registry.py --check         # exit 1 when the checked-in header is not what the ledger gives
    python tools/ledger_registry.py presets [--language <tag>|original|all] [--tsv <path>]

The ledger-fields round's stage D (docs/ledger-fields-round.md section 5): one
record per entry of docs/DIVERGENCE.md - id, title, tier, state, the
`Switch:` names each with its form, `Default:`, `Player:`, `Toward:`,
`Languages:` - generated by the same parsing tools/ledger_switches.py does
(`ledger_entries`, `field`, imported, not copied). The header is a constexpr
table of plain structs, string views and small enums and bit sets: no
allocation, no parser in the launcher. Reads only docs/DIVERGENCE.md and
tools/language_tags.py, no game data and no build tree, so it runs in CI
(.github/workflows/checks.yml): `--check` regenerates to memory and fails with
a summary of what differs.

The values are read as the ledger has them; tools/ledger_check.py is what
checks them. This tool refuses only what it cannot put in the table (a tier,
value or form it does not know), so a malformed ledger fails here too and
never makes a header.

`presets` is the reference the launcher's presets must agree with (the
launcher's code is the next group's): for each preset and a language, which
entries it turns off, by which switch names, and which it leaves and why.
The rules are the owner's calls of 2026-10-27/28 as the round doc's section 5
"D1 as run" records them; `classify` below is the one place they are written.
"""
import argparse, difflib, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ledger_switches   # noqa: E402 - ledger_entries, field: the ledger's own parsing
import language_tags     # noqa: E402 - the engine's language tags

ROOT = ledger_switches.ROOT
HEADER = os.path.join('src', 'launcher', 'ledger_registry.h')

TIERS = ('Forced', 'Intent', 'Sensible', 'Extension')
PLAYERS = ('yes', 'cheap', 'costly', 'never')
TOWARD = ('psx', 'psp', 'pc')
LANGUAGES = tuple(language_tags.TAGS) + ('original',)
PRESETS = ('recommended', 'as-shipped', 'repaired', 'playstation')

# What a preset does with an entry, in the order the summary prints them.
ACTIONS = ('off', 'skipped-language', 'lang-governed', 'cannot', 'also-available')
# The entries a preset leaves alone without listing them, counted so the rows add up.
QUIET = ('never', 'already-off', 'inactive')


def value(chunk, name):
    """A switch field's value: the field's text before an optional " - <clause>"
    (the grammar of docs/DIVERGENCE.md "The switch fields")."""
    text = ledger_switches.field(chunk, name)
    if text is None:
        return None
    return text.split(' - ', 1)[0].strip()


def tokens(text):
    return [t.strip().strip('`') for t in text.split(',')]


def parse_switch(tok):
    """(form, key, value) for one `Switch:` name."""
    if tok == 'lang':
        return 'lang', 'lang', ''
    m = re.fullmatch(r'ini:([a-z_]+(?:\.[a-z_0-9]+)?)=(\S*)', tok)
    if m:
        return 'ini', m.group(1), m.group(2)
    m = re.fullmatch(r'env:(BOF3X_[A-Z0-9_]+)=(\S*)', tok)
    if m:
        return 'env', m.group(1), m.group(2)
    if re.fullmatch(r'[A-Za-z_]\w*', tok):
        return 'name', tok, ''
    return None


class Refused(Exception):
    pass


def records(text=None):
    """One dict per ledger entry, in the ledger's order."""
    out, problems = [], []
    for did, title, chunk, ln in ledger_switches.ledger_entries(text):
        where = f'docs/DIVERGENCE.md:{ln}: {did}'
        vals = {f: value(chunk, f) for f in ('Tier', 'Switch', 'Default', 'Player', 'Toward', 'Languages', 'State')}
        for f, v in vals.items():
            if not v:
                problems.append(f'{where}: no "{f}:" field')
        if any(not v for v in vals.values()):
            continue
        tier = vals['Tier'].split(' ')[0]
        if tier not in TIERS:
            problems.append(f'{where}: Tier {tier!r} is not one of {", ".join(TIERS)}')
        switches = []
        if vals['Switch'] != 'none':
            for t in tokens(vals['Switch']):
                p = parse_switch(t)
                if p is None:
                    problems.append(f'{where}: Switch name {t!r} has no form this tool knows')
                else:
                    switches.append((t,) + p)
        default = vals['Default']
        if default not in ('on', 'off'):
            problems.append(f'{where}: Default {default!r} is not on or off')
        player = vals['Player']
        if player not in PLAYERS:
            problems.append(f'{where}: Player {player!r} is not one of {", ".join(PLAYERS)}')
        toward = [] if vals['Toward'] == 'none' else tokens(vals['Toward'])
        if not set(toward) <= set(TOWARD):
            problems.append(f'{where}: Toward {vals["Toward"]!r} is not none or a list of {", ".join(TOWARD)}')
        langs = None if vals['Languages'] == 'any' else tokens(vals['Languages'])
        if langs is not None and not set(langs) <= set(LANGUAGES):
            problems.append(f'{where}: Languages {vals["Languages"]!r} is not any or a list of '
                            f'{", ".join(LANGUAGES)}')
        st, sup = vals['State'], 0
        m = re.fullmatch(r'superseded by DIV-(\d{4})', st)
        if m:
            st, sup = 'superseded', int(m.group(1))
        elif st not in ('active', 'withdrawn'):
            problems.append(f'{where}: State {st!r} is not active, withdrawn or superseded by DIV-NNNN')
        out.append({'id': did, 'num': int(did[4:]), 'title': title, 'tier': tier, 'state': st,
                    'superseded_by': sup, 'switches': switches, 'switch_text': vals['Switch'],
                    'default': default, 'player': player, 'toward': toward, 'languages': langs})
    if not out and not problems:
        problems.append('docs/DIVERGENCE.md: no entries read')
    if problems:
        raise Refused('\n'.join(problems))
    return out


# --- the header ---------------------------------------------------------------

def c_string(s):
    """A C++ string literal of s's UTF-8 bytes: printable ASCII as it is, every
    other byte as a three-digit octal escape (which no following digit can
    extend)."""
    out = []
    for b in s.encode('utf-8'):
        c = chr(b)
        if c in '\\"':
            out.append('\\' + c)
        elif 0x20 <= b < 0x7f:
            out.append(c)
        else:
            out.append('\\%03o' % b)
    return '"' + ''.join(out) + '"'


def enum_name(s):
    return ''.join(p.capitalize() for p in re.split(r'[^A-Za-z0-9]+', s) if p)


LANG_CONST = {t: 'kLang' + enum_name(t) for t in LANGUAGES}


def header(recs):
    tiers = {t: 'Tier::' + t for t in TIERS}
    players = {p: 'Player::' + p.capitalize() for p in PLAYERS}
    states = {'active': 'State::Active', 'withdrawn': 'State::Withdrawn', 'superseded': 'State::Superseded'}
    forms = {'name': 'SwitchForm::Name', 'ini': 'SwitchForm::Ini', 'env': 'SwitchForm::Env',
             'lang': 'SwitchForm::Lang'}
    L = []
    w = L.append
    w('// GENERATED by tools/ledger_registry.py from docs/DIVERGENCE.md - do not edit.')
    w('// Regenerate with `python tools/ledger_registry.py`; CI runs it with --check and')
    w('// fails when this file is not what the ledger gives (.github/workflows/checks.yml).')
    w('//')
    w("// The ledger's switch fields, one record per entry (docs/DIVERGENCE.md \"The")
    w('// switch fields\", docs/ledger-fields-round.md section 5): what turns each entry')
    w("// off, whether the player's build can, and where it acts. The launcher's presets")
    w('// read it; `python tools/ledger_registry.py presets` is their reference. Titles')
    w("// and values are the project's own text, no game data (CLAUDE.md rule 1).")
    w('#pragma once')
    w('')
    w('#include <cstddef>')
    w('#include <cstdint>')
    w('#include <string_view>')
    w('')
    w('namespace bof3x::ledger {')
    w('')
    w('// The Tier field (docs/DIVERGENCE.md "Tiers").')
    w('enum class Tier : std::uint8_t { ' + ', '.join(TIERS) + ' };')
    w("// The Player field: whether bof3x.exe can turn the entry off.")
    w('enum class Player : std::uint8_t { ' + ', '.join(p.capitalize() for p in PLAYERS) + ' };')
    w('// The State field; a superseded entry names its successor in superseded_by.')
    w('enum class State : std::uint8_t { Active, Withdrawn, Superseded };')
    w('// A Switch: name\'s form: a BOF3X_ORIGINAL name (key = the name), ini:<key>=<value>,')
    w('// env:<BOF3X_NAME>=<value> (an empty value means unset), or lang (the language box).')
    w('enum class SwitchForm : std::uint8_t { Name, Ini, Env, Lang };')
    w('')
    w('// The Toward field, a bit set; 0 is `none`.')
    for i, t in enumerate(TOWARD):
        w(f'inline constexpr std::uint8_t kToward{enum_name(t)} = 0x{1 << i:02x};')
    w('// The Languages field, a bit set in tools/language_tags.py TAGS order and')
    w('// `original`; kLangAny alone is `any` (the entry does not depend on the language).')
    for i, t in enumerate(LANGUAGES):
        w(f'inline constexpr std::uint8_t {LANG_CONST[t]} = 0x{1 << i:02x};   // {t}')
    w('inline constexpr std::uint8_t kLangAny = 0x80;')
    w('')
    w('// The key and the value are spans of the text, not literals of their own, so')
    w('// that no environment name stands alone as a string here: tools/ledger_switches.py')
    w('// counts a "BOF3X_..." literal in src/ as a reader of that name.')
    w('struct Switch {')
    w('    SwitchForm form;')
    w('    std::string_view text;    // as the ledger writes it: `SunderLoop`, `ini:wide=0`')
    w('    std::uint8_t key_at;      // Key(): the name, the ini key, the environment name, or "lang"')
    w('    std::uint8_t key_len;')
    w('};')
    w('')
    w('constexpr std::string_view Key(const Switch& s) { return s.text.substr(s.key_at, s.key_len); }')
    w('// The value that turns the entry off: ini and env only, empty for the others')
    w('// (an empty env value means unset).')
    w('constexpr std::string_view Value(const Switch& s) {')
    w('    return s.form == SwitchForm::Ini || s.form == SwitchForm::Env ? s.text.substr(s.key_at + s.key_len + 1)')
    w('                                                                   : std::string_view();')
    w('}')
    w('')
    w('struct Entry {')
    w('    std::uint16_t id;              // DIV-nnnn')
    w('    std::string_view title;')
    w('    Tier tier;')
    w('    State state;')
    w('    std::uint16_t superseded_by;   // DIV-nnnn when state is Superseded, else 0')
    w('    std::uint16_t first_switch;    // into kSwitches')
    w('    std::uint8_t switch_count;     // 0 is `Switch: none`')
    w('    bool default_on;')
    w('    Player player;')
    w('    std::uint8_t toward;           // kToward* bits')
    w('    std::uint8_t languages;        // kLang* bits, or kLangAny')
    w('};')
    w('')
    sw_rows, first = [], {}
    for r in recs:
        first[r['id']] = len(sw_rows)
        for text, form, key, val in r['switches']:
            at = text.index(key)
            if text[at + len(key):] != (f'={val}' if form in ('ini', 'env') else '') or len(text) > 255:
                raise Refused(f'{r["id"]}: Switch name {text!r} does not split as {form} {key!r} = {val!r}')
            sw_rows.append(f'    {{{forms[form]}, {c_string(text)}, {at}, {len(key)}}},   // {r["id"]}')
    w(f'inline constexpr std::size_t kSwitchCount = {len(sw_rows)};')
    w('inline constexpr Switch kSwitches[kSwitchCount] = {')
    L.extend(sw_rows)
    w('};')
    w('')
    w(f'inline constexpr std::size_t kEntryCount = {len(recs)};')
    w('inline constexpr Entry kEntries[kEntryCount] = {')
    for r in recs:
        tw = ' | '.join(f'kToward{enum_name(t)}' for t in r['toward']) or '0'
        lg = 'kLangAny' if r['languages'] is None else ' | '.join(LANG_CONST[t] for t in r['languages'])
        w(f'    {{{r["num"]}, {c_string(r["title"])},')
        w(f'     {tiers[r["tier"]]}, {states[r["state"]]}, {r["superseded_by"]}, {first[r["id"]]}, '
          f'{len(r["switches"])}, {"true" if r["default"] == "on" else "false"}, {players[r["player"]]}, '
          f'{tw}, {lg}}},')
    w('};')
    w('')
    w('// The switches of one entry.')
    w('constexpr const Switch* SwitchesBegin(const Entry& e) { return kSwitches + e.first_switch; }')
    w('constexpr const Switch* SwitchesEnd(const Entry& e) { return kSwitches + e.first_switch + e.switch_count; }')
    w('// Whether the language pick governs the entry (its Languages is a list, not any).')
    w('constexpr bool LanguageGoverned(const Entry& e) { return e.languages != kLangAny; }')
    w('// Whether the entry acts under a language (one kLang* bit).')
    w('constexpr bool ActsUnder(const Entry& e, std::uint8_t lang) {')
    w('    return e.languages == kLangAny || (e.languages & lang) != 0;')
    w('}')
    w('// The entry for DIV-id, or nullptr.')
    w('constexpr const Entry* Find(std::uint16_t id) {')
    w('    for (const Entry& e : kEntries)')
    w('        if (e.id == id) return &e;')
    w('    return nullptr;')
    w('}')
    w('')
    w('// The table is whole: ids rise, every entry\'s switches lie inside kSwitches.')
    w('constexpr bool TableIsWhole() {')
    w('    std::size_t next = 0;')
    w('    for (std::size_t i = 0; i < kEntryCount; ++i) {')
    w('        if (i > 0 && kEntries[i].id <= kEntries[i - 1].id) return false;')
    w('        if (kEntries[i].first_switch != next) return false;')
    w('        next += kEntries[i].switch_count;')
    w('    }')
    w('    for (const Switch& s : kSwitches)')
    w('        if (s.key_len == 0 || s.key_at + s.key_len > s.text.size()) return false;')
    w('    return next == kSwitchCount;')
    w('}')
    w('static_assert(TableIsWhole(), "ledger_registry.h: regenerate with tools/ledger_registry.py");')
    w('')
    w('}  // namespace bof3x::ledger')
    out = '\n'.join(L) + '\n'
    lit = ledger_switches.ENV_LIT.search(out)
    if lit:
        raise Refused(f'the header would hold the literal "{lit.group(1)}", which tools/ledger_switches.py '
                      'would count as a reader of that name')
    return out


# --- the presets --------------------------------------------------------------

def wants_off(preset, r):
    if preset == 'recommended':
        return False
    if preset == 'as-shipped':
        return True
    if preset == 'repaired':
        return r['tier'] in ('Sensible', 'Extension')
    if preset == 'playstation':
        # The owner's call of 2026-10-28: `Toward: none` is a generic repair,
        # tied to no release, and stays; only an entry that names a release
        # and not the PlayStation (`psp` alone, `pc`) is turned off.
        return bool(r['toward']) and 'psx' not in r['toward']
    raise ValueError(preset)


def wants_on(preset, r):
    """The entries a preset keeps on by its own rule (not merely leaves at the
    default): Repaired keeps Intent and Forced, PlayStation every `psx`."""
    if preset == 'repaired':
        return r['tier'] in ('Intent', 'Forced')
    if preset == 'playstation':
        return 'psx' in r['toward']
    return False


def classify(preset, r, lang):
    """(action, reason) for one entry under a preset and a language, or None
    when the preset has nothing to do with it. The rules, in the order they
    apply (docs/ledger-fields-round.md section 5, "D1 as run")."""
    off, on = wants_off(preset, r), wants_on(preset, r)
    if not off and not (on and r['default'] == 'off'):
        return None
    if r['state'] != 'active':
        return 'inactive', f'State {r["state"]}: no preset switches it'
    if r['languages'] is not None and lang not in r['languages']:
        return 'skipped-language', f'acts only under {", ".join(r["languages"])}'
    if not off:
        return 'also-available', 'Default off: the preset keeps it on, so switch it on yourself'
    if r['default'] == 'off':
        return 'already-off', 'Default off: already off'
    if any(s[1] == 'lang' for s in r['switches']):
        return 'lang-governed', 'Switch: lang - part of the language pick, which no preset changes'
    if r['player'] == 'never':
        return 'never', 'Player never: Forced or one-way'
    if r['player'] == 'costly':
        return 'cannot', "Player costly: the original is only Capcom's function; this build cannot"
    note = 'Player cheap, read as yes until the player\'s switch is built' if r['player'] == 'cheap' else 'Player yes'
    return 'off', note


def preset_rows(recs, lang):
    rows = []
    for p in PRESETS:
        for r in recs:
            c = classify(p, r, lang)
            if c:
                rows.append({'language': lang, 'preset': p, 'action': c[0], 'id': r['id'],
                             'switch': r['switch_text'], 'title': r['title'], 'reason': c[1]})
    return rows


def print_presets(recs, lang, rows):
    cheap = sum(1 for r in recs if r['player'] == 'cheap')
    print(f'language {lang}; {len(recs)} entries' + (
        f'; {cheap} Player cheap read as yes (the rule until the player\'s switch is built)' if cheap else ''))
    for p in PRESETS:
        mine = [x for x in rows if x['preset'] == p]
        n = {a: sum(1 for x in mine if x['action'] == a) for a in ACTIONS + QUIET}
        print()
        print(f'== {p}: off {n["off"]}, skipped by language {n["skipped-language"]}, lang-governed '
              f'{n["lang-governed"]}, cannot {n["cannot"]}, also available {n["also-available"]} '
              f'(left alone: never {n["never"]}, already off {n["already-off"]}, not active {n["inactive"]})')
        for a in ACTIONS:
            items = [x for x in mine if x['action'] == a]
            if not items:
                continue
            print(f'  -- {a} ({len(items)})')
            for x in items:
                print(f'  {x["id"]}  {x["switch"]}  {x["title"]}')


def write_tsv(path, rows):
    cols = ('language', 'preset', 'action', 'id', 'switch', 'title', 'reason')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# tools/ledger_registry.py presets - what each preset does with each entry it concerns.\n')
        f.write('# Generated from docs/DIVERGENCE.md; no game data. action: '
                + ' | '.join(ACTIONS + QUIET) + '\n')
        f.write('\t'.join(cols) + '\n')
        for x in rows:
            f.write('\t'.join(x[c].replace('\t', ' ') for c in cols) + '\n')


# --- main ---------------------------------------------------------------------

def read_ledger(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--ledger', default=os.path.join(ROOT, ledger_switches.LEDGER),
                    help='the ledger to read (default docs/DIVERGENCE.md)')
    ap.add_argument('--header', default=os.path.join(ROOT, HEADER),
                    help='the header to write or check (default src/launcher/ledger_registry.h)')
    ap.add_argument('--check', action='store_true', help='compare the header with the ledger; write nothing')
    sub = ap.add_subparsers(dest='cmd')
    pp = sub.add_parser('presets', help='what each preset turns off, under a language')
    pp.add_argument('--language', default='original',
                    help='a tag of tools/language_tags.py, original (default), or all')
    pp.add_argument('--tsv', help='also write the rows to this path')
    a = ap.parse_args()

    try:
        recs = records(read_ledger(a.ledger))
    except Refused as e:
        for line in str(e).split('\n'):
            print(f'error: {line}')
        return 1

    if a.cmd == 'presets':
        langs = LANGUAGES[-1:] + LANGUAGES[:-1] if a.language == 'all' else (a.language,)
        bad = [x for x in langs if x not in LANGUAGES]
        if bad:
            print(f'error: --language {bad[0]}: not one of {", ".join(LANGUAGES)}, or all')
            return 2
        rows = []
        for i, lang in enumerate(langs):
            mine = preset_rows(recs, lang)
            if i:
                print()
            print_presets(recs, lang, mine)
            rows += mine
        if a.tsv:
            write_tsv(a.tsv, rows)
            print(f'\nwrote {a.tsv} ({len(rows)} rows)')
        return 0

    try:
        want = header(recs)
    except Refused as e:
        print(f'error: {e}')
        return 1
    rel = os.path.relpath(os.path.abspath(a.header), ROOT).replace(os.sep, '/')
    if a.check:
        try:
            with open(a.header, encoding='utf-8', newline='') as f:
                have = f.read().replace('\r\n', '\n')   # a Windows checkout's line ends
        except FileNotFoundError:
            print(f'error: {rel} is missing; run python tools/ledger_registry.py')
            return 1
        if have == want:
            print(f'ledger_registry: {rel} is what the ledger gives ({len(recs)} entries)')
            return 0
        diff = list(difflib.unified_diff(have.split('\n'), want.split('\n'), rel + ' (checked in)',
                                         rel + ' (from the ledger)', n=0, lineterm=''))
        changed = sum(1 for d in diff if d[:1] in '+-' and not d.startswith(('+++', '---')))
        src = os.path.relpath(os.path.abspath(a.ledger), ROOT).replace(os.sep, '/')
        print(f'error: {rel} is not what {src} gives ({changed} lines differ); '
              'run python tools/ledger_registry.py and commit the header')
        for d in diff[:40]:
            print('  ' + d)
        if len(diff) > 40:
            print(f'  ... {len(diff) - 40} more diff lines')
        return 1
    os.makedirs(os.path.dirname(os.path.abspath(a.header)), exist_ok=True)
    with open(a.header, 'w', encoding='utf-8', newline='\n') as f:
        f.write(want)
    print(f'wrote {rel} ({len(recs)} entries, {want.count(chr(10))} lines)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
