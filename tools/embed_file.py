#!/usr/bin/env python
"""Write files as byte arrays in one C++ source (the drawn launcher's built-in files).

    python tools/embed_file.py OUT.cpp NAME FILE [NAME FILE]...

For each pair the source defines, in namespace bof3x::ui:

    extern const unsigned char NAME[];
    extern const unsigned NAME##Size;

src/launcher/ui/assets.h declares them. One mechanism for Windows and Linux,
where the Win32 launcher uses a resource (docs/launcher-portable.md, stage P1).
The output is written only when it changes, so a build with the same files
compiles nothing again.
"""
import os
import sys


def main(argv):
    if len(argv) < 4 or len(argv) % 2 != 0:
        sys.stderr.write(__doc__)
        return 2
    out, pairs = argv[1], argv[2:]
    lines = ['// Generated by tools/embed_file.py. Do not edit.',
             'namespace bof3x::ui {']
    for name, path in zip(pairs[0::2], pairs[1::2]):
        if not name.isidentifier():
            sys.stderr.write('embed_file.py: %r is not a C++ name\n' % name)
            return 2
        with open(path, 'rb') as f:
            data = f.read()
        lines.append('extern const unsigned char %s[] = {' % name)
        for at in range(0, len(data), 32):
            lines.append(','.join('%d' % b for b in data[at:at + 32]) + ',')
        lines.append('};')
        lines.append('extern const unsigned %sSize = %d;' % (name, len(data)))
    lines.append('}  // namespace bof3x::ui')
    text = '\n'.join(lines) + '\n'
    try:
        with open(out, 'r', encoding='ascii') as f:
            if f.read() == text:
                return 0
    except OSError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w', encoding='ascii', newline='\n') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
