#!/usr/bin/env python
"""Generates src/media/resample_table.h: the polyphase low-pass of the XA clip
resampler (src/media/resample.h, docs/psx-media-round.md 2.2).

    python tools/gen_resample.py           write the header
    python tools/gen_resample.py --check   the header on disk is what this makes today (any system)

One prototype serves both ratios. The input is taken up by L = 7 and the
filtered stream is read every M-th sample: M = 6 gives 37,800 -> 44,100 Hz,
M = 3 gives 18,900 -> 44,100 Hz. The cut-off is a fixed fraction of the
input's own Nyquist rate (the same normalised filter at either input rate), a
Kaiser-windowed sinc, 2 * HALF taps a phase.

The numbers are made with `decimal` at 60 digits, no float, so the header
does not depend on a platform's libm. Each phase is scaled so that its taps
sum to exactly 65,536 (unity gain at DC for every output position).
"""
import argparse
import os
import sys
from decimal import Decimal, getcontext

getcontext().prec = 60
L = 7
HALF = 24                      # taps a phase = 2 * HALF
BETA = Decimal("5.65")         # Kaiser; about 60 dB of stop-band
CUTOFF = Decimal("0.066")      # cycles per sample of the L-times rate; the input's Nyquist is 1/14
ONE = 65536
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "media", "resample_table.h")
PI = Decimal("3.14159265358979323846264338327950288419716939937510582097494")


def sin(x):
    """Taylor series: `decimal` has no sine, and a libm one would tie the table to a platform."""
    term, total, n = x, x, 1
    while abs(term) > Decimal(10) ** -55:
        term = -term * x * x / ((n + 1) * (n + 2))
        total += term
        n += 2
    return total


def i0(x):
    """Modified Bessel function of the first kind, order 0 (the Kaiser window's normaliser)."""
    term, total, k = Decimal(1), Decimal(1), 1
    q = x * x / 4
    while term > Decimal(10) ** -55:
        term = term * q / (k * k)
        total += term
        k += 1
    return total


def proto(m):
    """h[m] for -L*HALF <= m < L*HALF: the windowed sinc, gain L."""
    n = L * HALF
    if m == 0:
        s = 2 * CUTOFF
    else:
        x = 2 * PI * CUTOFF * m
        s = sin(x) / (PI * m)
    r = Decimal(m) / n
    w = i0(BETA * (1 - r * r).sqrt()) / i0(BETA)
    return L * s * w


def table():
    rows = []
    for r in range(L):
        h = [proto(r + L * (HALF - 1 - t)) for t in range(2 * HALF)]
        scale = Decimal(ONE) / sum(h)
        q = [int((v * scale).to_integral_value()) for v in h]
        # Rounding leaves the sum a few units off 65,536; the largest tap takes the error.
        big = max(range(len(q)), key=lambda i: abs(q[i]))
        q[big] += ONE - sum(q)
        rows.append(q)
    return rows


def render():
    lines = [
        "// GENERATED by tools/gen_resample.py; do not edit by hand (--check compares).",
        "// The resampler's polyphase low-pass: kResampleTaps[phase][tap], Q16, each phase's",
        "// taps summing to 65,536. Phase r, tap t is the prototype at r + 7 * (kResampleHalf - 1 - t).",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace media {",
        "",
        "constexpr int kResampleUp = %d;" % L,
        "constexpr int kResampleHalf = %d;" % HALF,
        "constexpr int kResampleOne = %d;" % ONE,
        "",
        "constexpr std::int32_t kResampleTaps[kResampleUp][2 * kResampleHalf] = {",
    ]
    for q in table():
        lines.append("    {")
        for i in range(0, len(q), 8):
            lines.append("        " + ", ".join("%d" % v for v in q[i:i + 8]) + ",")
        lines.append("    },")
    lines += ["};", "", "}  // namespace media", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="compare the header with today's output; write nothing")
    a = ap.parse_args()
    text = render()
    if a.check:
        have = open(OUT, "rb").read().decode("utf-8") if os.path.exists(OUT) else None
        if have != text:
            sys.exit("%s is not what tools/gen_resample.py makes; run it without --check" % OUT)
        print("%s is current" % OUT)
        return
    with open(OUT, "w", newline="\n") as f:
        f.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
