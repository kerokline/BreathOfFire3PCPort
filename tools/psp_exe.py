NAME_RECORD = 0x40          # BOOT.BIN's file table: one path record per disc file id
R_MIPS_32, R_MIPS_HI16, R_MIPS_LO16 = 2, 5, 6


def fail(msg):
    raise SystemExit("psp_exe: " + msg)


# ------------------------------------------------------------------ BOOT.BIN

class Elf:
    """PSP_GAME/SYSDIR/BOOT.BIN: its first program header as an image at link-time
    offset 0 (tools/psp_elf.py's convention), its sections and its relocations."""

    def __init__(self, raw):
        if raw[:4] != b"\x7fELF" or struct.unpack_from("<H", raw, 18)[0] != 8:
            fail("BOOT.BIN is not a plain MIPS ELF")
        shoff, = struct.unpack_from("<I", raw, 32)
        shsz, shn, shstr = struct.unpack_from("<HHH", raw, 46)
        shs = [struct.unpack_from("<10I", raw, shoff + i * shsz) for i in range(shn)]
        so = shs[shstr][4]
        self.sections = {}
        rels = []
        for s in shs:
            name = raw[so + s[0]:raw.index(b"\0", so + s[0])].decode()
            self.sections[name] = (s[3], s[5])                    # address, size
            if name.startswith(".rel"):
                rels.append((name[4:], s[4], s[5]))
        phoff, = struct.unpack_from("<I", raw, 28)
        _, off, va, _, fs, _, _, _ = struct.unpack_from("<8I", raw, phoff)
        if va != 0:
            fail("BOOT.BIN's first program header is not at 0")
        self.img = raw[off:off + fs]
        self.rel = {}
        for name, off, size in rels:
            self.rel[name] = [struct.unpack_from("<II", raw, off + 8 * i) for i in range(size // 8)]

    def span(self, name):
        a, n = self.sections[name]
        return a, a + n

    def word(self, a):
        return struct.unpack_from("<I", self.img, a)[0]

    @functools.cached_property
    def data_pointers(self):
        """The .data words a R_MIPS_32 relocation names (the ELF's pointer words)."""
        return {off for off, info in self.rel.get(".data", []) if info & 0xFF == R_MIPS_32}


def boot_bin(disc):
    return Elf(disc.read("PSP_GAME/SYSDIR/BOOT.BIN"))


def disc_paths(disc):
    """The disc's game files as BOOT.BIN names them: USRDIR/<language>/ stripped."""
    out = set()
    for p in disc.files:
        m = re.match(r"PSP_GAME/USRDIR/[^/]+/(.+)$", p)
        if m:
            out.add(m.group(1))
    return out


def file_table(elf, paths):
    """[path by disc file id] from BOOT.BIN's table of NAME_RECORD-byte path records,
    found by the disc's own paths: the start most of them agree on, walking back
    record by record while a record holds a path, then forward the same way."""
    lo, hi = elf.span(".data")
    ok = re.compile(rb"[A-Z0-9_]+(/[A-Z0-9_]+)*\.[A-Z0-9]+")

    def path_at(a):
        if a < lo or a + NAME_RECORD > hi:
            return None
        p = elf.img[a:a + NAME_RECORD].split(b"\0")[0]
        return p.decode() if ok.fullmatch(p) else None
    starts = collections.Counter()
    for p in sorted(paths)[::16]:
        a = elf.img.find(p.encode() + b"\0", lo, hi)
        if a < 0:
            continue
        while path_at(a - NAME_RECORD):
            a -= NAME_RECORD
        starts[a] += 1
    if not starts:
        fail("BOOT.BIN holds no table of the disc's paths")
    a = starts.most_common(1)[0][0]
    out = []
    while path_at(a + NAME_RECORD * len(out)):
        out.append(path_at(a + NAME_RECORD * len(out)))
    on_disc = sum(1 for p in out if p in paths)
    if on_disc * 10 < len(out) * 9:
        fail("BOOT.BIN's path table: only %d of %d records name a file on the disc" % (on_disc, len(out)))
    return out


def lba_table(disc, srcs):
    """[path by disc file id] on a PSX disc: the boot EXE's table of start sectors, one
    u32 per disc file - found as the longest run of aligned words in the boot EXE each
    of which is the start sector of a file on the disc (the disc's own directory) -
    each sector named by its file. The leading BIN/ is dropped, as BOOT.BIN's names
    have no such folder."""
    by_lba = {lba: p for p, (lba, size) in disc.files.items()}
    base, blob = srcs[("BOOT", None)]
    best = (0, 0)
    a = 0
    while a + 4 <= len(blob):
        n = 0
        while a + 4 * (n + 1) <= len(blob) and struct.unpack_from("<I", blob, a + 4 * n)[0] in by_lba:
            n += 1
        if n > best[1]:
            best = (a, n)
        a += 4 * max(n, 1)
    a, n = best
    if n < len(by_lba) // 2:
        fail("the boot EXE holds no table of the disc's start sectors (the longest run: %d of %d files)" % (n, len(by_lba)))
    paths = [by_lba[struct.unpack_from("<I", blob, a + 4 * i)[0]] for i in range(n)]
    return [p[4:] if p.startswith("BIN/") else p for p in paths]


def disc_ids(disc, bid, srcs, elf=None):
    """[path by disc file id]: BOOT.BIN's path records on a PSP disc, the boot EXE's
    sector table on a PSX one."""
    if bid in PSP:
        return file_table(elf or boot_bin(disc), disc_paths(disc))
    return lba_table(disc, srcs)


# ------------------------------------------------------------------ the PC's file ids

def data_symbol(name):
    with open(os.path.join(ROOT, "symbols.toml"), "rb") as f:
        for e in tomllib.load(f)["data"]:
            if e["name"] == name:
                return e
    fail("symbols.toml has no [[data]] %s" % name)


@functools.lru_cache(None)
def pc_file_ids():
    """({DAT name: PC file id}, set of null ids) from Dat_FileNames' layout words
    (recipes/exe-layout.tsv) into the name pool exe_own.cpp lays downward from its
    region's top in recipes/pc-zh.toml's order."""
    import exe_own
    import exe_tables
    with open(os.path.join(ROOT, "recipes", "pc-zh.toml"), "rb") as f:
        names = [x["name"] for x in tomllib.load(f)["file"]]
    pool = [r for r in exe_own.own_regions() if r[2].startswith("Dat_FileNames")]
    if len(pool) != 1:
        fail("src/hook/exe_own.cpp has no single Dat_FileNames name pool")
    lo, top, _ = pool[0]
    at = {}
    for n in names:
        top -= (len(n) + 1 + 3) & ~3          # exe_own.cpp's Slot()
        at[top] = n
    if top != lo:
        fail("the DAT name pool does not fill its region")
    sym = data_symbol("Dat_FileNames")
    first, count = sym["pc"], sym["count"]
    ids = {}
    for a, kind, t in exe_tables.load_layout():
        if first <= a < first + 4 * count:
            if kind != "data" or int(t, 16) not in at:
                fail("exe-layout.tsv 0x%06X: not a word into the DAT name pool" % a)
            ids[at[int(t, 16)]] = (a - first) // 4
    if len(ids) != len(names):
        fail("Dat_FileNames' layout names %d of %d DAT files" % (len(ids), len(names)))
    return ids, set(range(count)) - set(ids.values())


def id_rule(table):
    """{disc file id: PC file id}. By name: the path's stem + .DAT. A disc file the PC
    ships no DAT for: its directory's displacement, when the named ids on either side
    in that directory agree on it and the slot is one Dat_FileNames leaves null."""
    ids, null = pc_file_ids()
    stem = lambda p: p.rsplit("/", 1)[-1].rsplit(".", 1)[0] + ".DAT"
    rule = {d: ids[stem(p)] for d, p in enumerate(table) if stem(p) in ids}
    for d, p in enumerate(table):
        if d in rule:
            continue
        folder = p.split("/")[0]
        below = [rule[e] - e for e in range(d - 1, -1, -1) if e in rule and table[e].split("/")[0] == folder][:1]
        above = [rule[e] - e for e in range(d + 1, len(table)) if e in rule and table[e].split("/")[0] == folder][:1]
        if below and below == above and d + below[0] in null and d + below[0] not in rule.values():
            rule[d] = d + below[0]
    return rule


def map_ids(rule, v, keep=(0, 0xFFFF)):
    if v in keep:
        return v
    if v not in rule:
        raise KeyError(v)
    return rule[v]


# ------------------------------------------------------------------ the finds

def sources_of(disc):
    import exe_twins
    return {(f, s): (base, blob) for f, s, base, blob in exe_twins.sources(disc)}


def find_rows8(elf):
    """Magic_Rows in BOOT.BIN: the one run in .data of exactly the PC's row count of
    stride-8 rows whose +4 word a relocation points into .text and whose +0 word none
    does. (address, rows)."""
    sym = data_symbol("Magic_Rows")
    rows = sym["count"] // 2
    lo, hi = elf.span(".data")
    tlo, thi = elf.span(".text")
    ptr = elf.data_pointers

    def row(a):
        return (a + 4) in ptr and a not in ptr and tlo <= elf.word(a + 4) < thi
    runs = []
    for phase in (0, 4):
        a = lo + phase
        while a + 8 <= hi:
            n = 0
            while a + 8 * (n + 1) <= hi and row(a + 8 * n):
                n += 1
            if n:
                runs.append((a, n))
            a += 8 * max(n, 1)
    hits = [a for a, n in runs if n == rows]
    if len(hits) != 1:
        fail("BOOT.BIN: %d runs of %d code-pointer rows (want one)" % (len(hits), rows))
    return hits[0], rows


def find_rows8_psx(srcs, file):
    """Magic_Rows on a PSX disc: in the sections of `file` (the battle engine's, the
    file exe_maps places Effect_HpDamageVariance from), the one run of exactly the
    PC's row count of stride-8 rows whose +4 word is a main-RAM code address
    (4-aligned, 0x80010000..0x80200000) and whose +0 word is no such address.
    (section, address, rows)."""
    rows = data_symbol("Magic_Rows")["count"] // 2
    hits = []
    for (f, s), (base, blob) in sorted(srcs.items(), key=lambda kv: (kv[0][0], kv[0][1] or 0)):
        if f != file:
            continue

        def row(a):
            w0, w4 = struct.unpack_from("<II", blob, a)
            return 0x80010000 <= w4 < 0x80200000 and w4 % 4 == 0 and not 0x80000000 <= w0 < 0x80200000
        for phase in (0, 4):
            a = phase
            while a + 8 <= len(blob):
                n = 0
                while a + 8 * (n + 1) <= len(blob) and row(a + 8 * n):
                    n += 1
                if n == rows:
                    hits.append((s, base + a))
                a += 8 * max(n, 1)
    if len(hits) != 1:
        fail("%s: %d runs of %d code-pointer rows (want one)" % (file, len(hits), rows))
    return hits[0][0], hits[0][1], rows


def event_place(bid):
    """BOOT.BIN's u16 file array of EventBattle_Records: the catalogued table's place
    in this build + its count x stride (on the PC the (file, track) pairs follow it at
    the same offset)."""
    import tables
    cat, syms, _ = tables.load()
    t = next(t for t in cat["table"] if t.get("symbol") == "EventBattle_Records")
    rows = [p for p in t.get("psx", []) if p["build"] == bid]
    rows.sort(key=lambda p: p["file"] != "BOOT.BIN")          # on a PSP disc the ELF's copy
    if not rows:
        fail("tables.toml has no place of EventBattle_Records for %s" % bid)
    return syms[t["symbol"]], rows[0]["file"], rows[0].get("section"), rows[0]["addr"], t["count"], t["stride"]


def hole_segments(bid, lo):
    """The exe_maps/<build>.tsv segments either side of the unplaced run holding `lo`
    when they are one file at one displacement: (file, section, disc address of lo)."""
    import tables
    segs = sorted(tables.read_map(os.path.join(tables.MAPS, bid + ".tsv")), key=lambda r: r["pc"])
    k = bisect.bisect_right([r["pc"] for r in segs], lo) - 1
    a, b = segs[k], segs[k + 1]
    if not (a["pc_end"] <= lo < b["pc"]) or (a["file"], a["section"]) != (b["file"], b["section"]) \
            or a["addr"] - a["pc"] != b["addr"] - b["pc"]:
        return None
    return a["file"], a["section"], a["addr"] - a["pc"] + lo, b["pc"]


# ------------------------------------------------------------------ the fills

def build_fill(row, disc, elf, rule, srcs):
    """One recipe row's bytes: (pc, bytes, mask) - mask True where the byte is the
    rule's to write (False: left to whatever else fills it)."""
    rl, lo, hi = row["rule"], row["pc"], row["pc_end"]
    base, blob = (0, elf.img) if row["file"] == "BOOT.BIN" else srcs[(row["file"], row["section"])]
    at = row["addr"] - base
    out, mask = bytearray(hi - lo), [False] * (hi - lo)
    if rl == "rows8":
        for r in range((hi - lo) // 8):
            w0, w4 = struct.unpack_from("<II", blob, at + 8 * r)
            ok = ((at + 8 * r + 4) in elf.data_pointers and (at + 8 * r) not in elf.data_pointers) if elf else \
                (0x80010000 <= w4 < 0x80200000 and not 0x80000000 <= w0 < 0x80200000)
            if not ok:
                fail("%s: %s 0x%X row %d is no code-pointer row" % (row["build"], row["file"], row["addr"], r))
            f, x = struct.unpack_from("<HH", blob, at + 8 * r)
            struct.pack_into("<HH", out, 8 * r, map_ids(rule, f), x)
            mask[8 * r:8 * r + 4] = [True] * 4
    elif rl == "pairs":
        for i in range((hi - lo) // 4):
            f, = struct.unpack_from("<H", blob, at + 2 * i)
            struct.pack_into("<H", out, 4 * i, map_ids(rule, f))
            mask[4 * i:4 * i + 2] = [True] * 2
    elif rl == "holes":
        for i in range((hi - lo) // 2):
            v, = struct.unpack_from("<H", blob, at + 2 * i)
            struct.pack_into("<H", out, 2 * i, map_ids(rule, v, keep=(0,)))
            mask[2 * i:2 * i + 2] = [True] * 2
    elif rl.startswith("widen"):
        k = int(rl[5:])                                   # the disc's name width; its entry k + 12
        for i in range((hi - lo) // 28):
            out[28 * i + 16:28 * i + 28] = blob[at + (k + 12) * i + k:at + (k + 12) * i + k + 12]
            mask[28 * i + 16:28 * i + 28] = [True] * 12
    elif rl == "psxmap":
        out[:] = blob[at:at + hi - lo]
        mask = [True] * (hi - lo)
    else:
        fail("exe-psp.tsv: unknown rule %s" % rl)
    return lo, bytes(out), mask


def load_recipe(path=RECIPE):
    out = collections.defaultdict(list)
    if not os.path.exists(path):
        return out
    with open(path, encoding="utf-8") as f:
        lines = [l.rstrip("\n") for l in f if not l.startswith("#")]
    if not lines or lines[0].split("\t") != COLS:
        fail("exe-psp.tsv: the column line is not %s" % "\t".join(COLS))
    for l in lines[1:]:
        c = l.split("\t")
        out[c[0]].append({"build": c[0], "rule": c[1], "pc": int(c[2], 16), "pc_end": int(c[3], 16), "file": c[4],
                          "section": None if c[5] == "-" else int(c[5]), "addr": int(c[6], 16), "filled": int(c[7])})
    return out


def fill(disc, bid, owner, rows=None, srcs=None):
    """The PSP fills for a PSP build's image (exe_tables.disc_image's call): [(pc,
    bytes, where, disc address)] for the runs of each recipe row's bytes that nothing
    has filled yet. No row for another build. `srcs`: exe_twins.sources as
    {(file, section): (base, bytes)}, if the caller has it."""
    rows = load_recipe()[bid] if rows is None else rows
    if not rows or _RECIPE_BASE:
        return []
    elf = boot_bin(disc) if bid in PSP else None
    srcs = sources_of(disc) if srcs is None else srcs
    rule = id_rule(disc_ids(disc, bid, srcs, elf))
    out = []
    for row in rows:
        lo, raw, mask = build_fill(row, disc, elf, rule, srcs)
        where = "%s%s:%s" % (row["file"], "" if row["section"] is None else "#%d" % row["section"], row["rule"])
        i = 0
        while i < len(raw):
            if not mask[i] or owner[lo + i - DATA_LO] is not None:
                i += 1
                continue
            j = i
            while j < len(raw) and mask[j] and owner[lo + j - DATA_LO] is None:
                j += 1
            out.append((lo + i, raw[i:j], where, row["addr"]))
            i = j
    return out


# ------------------------------------------------------------------ recipe

def find_rows(disc, bid, pc):
    """Every fill this build's disc gives, located by the rules above and kept only
    where its bytes equal BOF3.exe's: recipe rows."""
    psp = bid in PSP
    elf = boot_bin(disc) if psp else None
    srcs = sources_of(disc)
    table = disc_ids(disc, bid, srcs, elf)
    rule = id_rule(table)
    print("  %s: %d disc file ids, %d with a PC file id" % (bid, len(table), len(rule)))
    rows = []
    sym = data_symbol("Magic_Rows")
    hv = data_symbol("Effect_HpDamageVariance")
    if psp:
        a, n = find_rows8(elf)
        f8, s8 = "BOOT.BIN", None
    else:
        import tables
        seg = next(r for r in tables.read_map(os.path.join(tables.MAPS, bid + ".tsv"))
                   if r["pc"] <= hv["pc"] < r["pc_end"])
        s8, a, n = find_rows8_psx(srcs, seg["file"])
        f8 = seg["file"]
    rows.append({"build": bid, "rule": "rows8", "pc": sym["pc"], "pc_end": sym["pc"] + 8 * n, "file": f8,
                 "section": s8, "addr": a})
    pcs, ef, es, place, count, stride = event_place(bid)
    eb, eblob = (0, elf.img) if ef == "BOOT.BIN" else srcs[(ef, es)]
    n_files = 1 + max(eblob[place - eb + stride * i + 3] for i in range(count))
    rows.append({"build": bid, "rule": "pairs", "pc": pcs + count * stride, "pc_end": pcs + count * stride + 4 * n_files,
                 "file": ef, "section": es, "addr": place + count * stride})
    lo = hv["pc"] + 2 * hv["count"]                       # the records after the s16 table
    import exe_tables
    targets = sorted({int(t, 16) for a_, k, t in exe_tables.load_layout() if lo <= a_ < lo + 0x100 and k == "data"})
    targets = [t for t in targets if t > lo]          # the records' own words end where the first table starts
    first, last = targets[0], targets[-1]
    span = min(b - a_ for a_, b in zip(targets, targets[1:]) if b - a_ >= 0x10)   # a table's length
    h = hole_segments(bid, first)
    if h:
        f, s, addr, _ = h
        rows.append({"build": bid, "rule": "holes", "pc": first, "pc_end": last + span, "file": f, "section": s,
                     "addr": addr})
    w = wheel_place(elf, pc) if psp else wheel_place_psx(srcs, pc)
    if w:
        rows.append({"build": bid, "rule": "widen%d" % w[5], "pc": w[0], "pc_end": w[1], "file": w[3],
                     "section": w[4], "addr": w[2]})
    kept = []
    for r in rows:
        lo_, raw, mask = build_fill(r, disc, elf, rule, srcs)
        bad = [i for i in range(len(raw)) if mask[i] and raw[i] != pc[lo_ + i - DATA_LO]]
        r["filled"] = sum(mask)
        print("  %s %-6s 0x%06X..0x%06X from %s%s 0x%X: %d bytes, %d not BOF3.exe's" % (
            bid, r["rule"], r["pc"], r["pc_end"], r["file"], "" if r["section"] is None else "#%d" % r["section"],
            r["addr"], r["filled"], len(bad)))
        if not bad:
            kept.append(r)
    if not psp:
        return kept
    taken = {x for r in kept for x in range(r["pc"], r["pc_end"])}
    psx = psxmap_rows(disc, bid, pc, srcs, taken)
    print("  %s psxmap: %d runs, %d bytes (%d of them non-zero on the PC) from the PSP's own files at %s's places" % (
        bid, len(psx), sum(r["filled"] for r in psx),
        sum(1 for r in psx for x in range(r["pc"], r["pc_end"]) if pc[x - DATA_LO]), PSX_MAP))
    return sorted(kept + psx, key=lambda r: r["pc"])


def psxmap_rows(disc, bid, pc, srcs, taken):
    """What the PSP build's image leaves unfilled that PSX_MAP's segments (exe_maps,
    exe-places.tsv) place from a file the PSP disc also has: each unfilled run of such
    a segment - not an engine-own byte, not a language range of exe-gaps.tsv, not a
    rule's - read from the PSP's file at the same address, kept only when the whole
    run equals BOF3.exe's and holds a non-zero byte."""
    import exe_tables
    import tables
    import psp_exe as imported      # exe_tables' copy (this file may be running as __main__)
    imported._RECIPE_BASE = True
    try:
        _, owner, _, _, _ = exe_tables.disc_built(disc, bid, exe_tables.load_pointers(),
                                                  exe_tables.load_rebuild_refused()[bid])
    finally:
        imported._RECIPE_BASE = False
    skip = set(taken) | exe_tables.own_bytes()
    gaps, _ = exe_tables.load_gaps()
    skip.update(x for lo, hi, how, _, _ in gaps.get(bid, []) if how == "language" for x in range(lo, hi))
    segs = tables.read_map(os.path.join(tables.MAPS, PSX_MAP + ".tsv")) + exe_tables.load_places().get(PSX_MAP, [])
    out = []
    for s in sorted(segs, key=lambda r: r["pc"]):
        if (s["file"], s["section"]) not in srcs:
            continue
        base, blob = srcs[(s["file"], s["section"])]
        x = s["pc"]
        while x < s["pc_end"]:
            if owner[x - DATA_LO] is not None or x in skip:
                x += 1
                continue
            y = x
            while y < s["pc_end"] and owner[y - DATA_LO] is None and y not in skip:
                y += 1
            at = s["addr"] + x - s["pc"] - base
            if blob[at:at + y - x] == pc[x - DATA_LO:y - DATA_LO] and any(pc[x - DATA_LO:y - DATA_LO]):
                out.append({"build": bid, "rule": "psxmap", "pc": x, "pc_end": y, "file": s["file"],
                            "section": s["section"], "addr": s["addr"] + x - s["pc"], "filled": y - x})
            x = y
    return out


def wheel_place(elf, pc):
    """The formation wheel's disc twin in BOOT.BIN: the PC's ten 28-byte entries (a
    16-byte name, three s16 spots) as 20-byte entries (an 8-byte name), found by the
    spots (BOF3.exe's, at recipe time only); the lowest of the copies, which must all
    be equal. (pc, pc_end, address) or None."""
    sym = data_symbol("Equip_SlotIcons")
    lo = sym["pc"] + 0x50
    n = 10
    spots = [pc[lo + 28 * i + 16 - DATA_LO:lo + 28 * i + 28 - DATA_LO] for i in range(n)]
    dlo, dhi = elf.span(".data")
    hits = []
    a = elf.img.find(spots[0], dlo, dhi)
    while a >= 0:
        if all(elf.img[a + 20 * i:a + 20 * i + 12] == spots[i] for i in range(n)):
            hits.append(a - 8)
        a = elf.img.find(spots[0], a + 1, dhi)
    if not hits:
        return None
    if len({elf.img[h:h + 20 * n] for h in hits}) != 1:
        fail("BOOT.BIN's copies of the formation wheel differ")
    return lo, lo + 28 * n, hits[0], "BOOT.BIN", None, 8


def wheel_place_psx(srcs, pc):
    """The formation wheel on a PSX disc: as wheel_place, in the EMIs (each menu
    overlay carries a copy, found by BOF3.exe's spots at recipe time); the first in
    path order, all copies' spots equal. (pc, pc_end, address, file, section) or None."""
    sym = data_symbol("Equip_SlotIcons")
    lo = sym["pc"] + 0x50
    n = 10
    spots = [pc[lo + 28 * i + 16 - DATA_LO:lo + 28 * i + 28 - DATA_LO] for i in range(n)]
    hits = []
    for (f, s), (base, blob) in sorted(srcs.items(), key=lambda kv: (kv[0][0], kv[0][1] or 0)):
        a = blob.find(spots[0])
        while a >= 0:
            for k in (8, 10, 12):                         # the disc's name width (the stride less the spots)
                if a >= k and all(blob[a + (k + 12) * i:a + (k + 12) * i + 12] == spots[i] for i in range(n)):
                    hits.append((f, s, base + a - k, k))
            a = blob.find(spots[0], a + 1)
    if not hits:
        return None
    f, s, addr, k = hits[0]
    return lo, lo + 28 * n, addr, f, s, k


def write_recipe(rows):
    lines = ["# recipes/exe-psp.tsv - GENERATED by `tools/psp_exe.py recipe`; do not edit.",
             "# The game values a PSP disc carries in another shape than BOF3.exe's (docs/psp-image.md):",
             "# per PSP build, the PC range [pc, pc_end) a rule fills from `file` (BOOT.BIN or an EMI and its",
             "# section) at `addr` - rows8 (Magic_Rows' file ids), pairs (EventBattle_Records' file array),",
             "# holes (Effect_HpDamageVariance's set-file tables), widen8 (the formation wheel's spots) - and",
             "# how many bytes it fills. A row is written only when every byte equals BOF3.exe's.",
             "# Addresses and counts only (CLAUDE.md rule 1).",
             "\t".join(COLS)]
    for r in rows:
        lines.append("%s\t%s\t0x%06X\t0x%06X\t%s\t%s\t0x%08X\t%d" % (
            r["build"], r["rule"], r["pc"], r["pc_end"], r["file"], "-" if r["section"] is None else r["section"],
            r["addr"], r["filled"]))
    with open(RECIPE, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


