def cmd_measure(a):
    """The PSP-built images against PSX-JP's, class by class: recipes/exe-gaps.tsv's
    rows (the ranges and bytes per class, and those only one side has), and the
    placed bytes that differ from BOF3.exe's, by symbol (exe_tables.disc_built)."""
    import exe_tables
    out = os.path.abspath(a.out)
    if out.startswith(ROOT + os.sep) and not out.startswith(os.path.join(ROOT, "analysis") + os.sep):
        fail("--out inside the repository must be under analysis/ (gitignored)")
    os.makedirs(out, exist_ok=True)
    pc, _ = exe_tables.pc_data(os.path.join(a.game, "BOF3.exe"))
    gaps, _ = exe_tables.load_gaps()
    syms = exe_tables.data_symbols()
    cover = {}
    for bid in gaps:
        cover[bid] = {x: (how, kind) for lo, hi, how, kind, _ in gaps[bid] for x in range(lo, hi)}
    report = {}
    pointers = exe_tables.load_pointers()
    refused = exe_tables.load_rebuild_refused()
    for bid, disc in exe_tables.discs(a.disc):
        img, owner, ranges, _, _ = exe_tables.disc_built(disc, bid, pointers, refused[bid])
        by_class = collections.Counter()
        for lo, hi, how, kind, _ in gaps[bid]:
            by_class["%s/%s ranges" % (how, kind)] += 1
            by_class["%s/%s bytes" % (how, kind)] += hi - lo
        differ = collections.defaultdict(collections.Counter)
        for i in range(len(pc)):
            if owner[i] is not None and img[i] != pc[i]:
                name, _ = exe_tables.symbol_at(syms, DATA_LO + i)
                differ[name][ranges[owner[i]][2]] += 1
        rep = {"gaps": dict(by_class), "placed_differ": {k: dict(v) for k, v in differ.items()},
               "identical": sum(x == y for x, y in zip(img, pc)),
               "filled_by_psp": sum(r[1] - r[0] for r in ranges if r[2] == "place" and ":" in r[3])}
        if bid != "psx-jp" and "psx-jp" in cover:
            only = collections.Counter()
            gone = collections.Counter()
            for x, c in cover[bid].items():
                if x not in cover["psx-jp"]:
                    only["/".join(c)] += 1
            for x, c in cover["psx-jp"].items():
                if x not in cover[bid]:
                    gone["/".join(c)] += 1
            rep["bytes in a row here, not on psx-jp"] = dict(only)
            rep["bytes in a row on psx-jp, not here"] = dict(gone)
        report[bid] = rep
        print("== %s: %d of %d bytes identical; placed and differing, by symbol:" % (bid, rep["identical"], len(pc)))
        for name, c in sorted(differ.items(), key=lambda kv: -sum(kv[1].values())):
            print("     %-34s %s" % (name, dict(c)))
    with open(os.path.join(out, "psp_measure.json"), "w") as f:
        json.dump(report, f, indent=1)
    print("-> %s" % out)


