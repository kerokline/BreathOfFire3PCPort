def find_rows(disc, bid, pc):
    """Every fill this build's disc gives, located by the rules above and kept only
    where its bytes equal BOF3.exe's: recipe rows."""
    psp = bid in PSP
    elf = boot_bin(disc) if psp else None
    srcs = sources_of(disc)
    table = disc_ids(disc, bid, srcs, elf)
    rule = id_rule(table)
    print("  %s: %d disc file ids, %d with a PC file id" % (bid, len(table), len(rule)))
    rows = []
    sym = data_symbol("Magic_Rows")
    hv = data_symbol("Effect_HpDamageVariance")
    if psp:
        a, n = find_rows8(elf)
        f8, s8 = "BOOT.BIN", None
    else:
        import tables
        seg = next(r for r in tables.read_map(os.path.join(tables.MAPS, bid + ".tsv"))
                   if r["pc"] <= hv["pc"] < r["pc_end"])
        s8, a, n = find_rows8_psx(srcs, seg["file"])
        f8 = seg["file"]
    rows.append({"build": bid, "rule": "rows8", "pc": sym["pc"], "pc_end": sym["pc"] + 8 * n, "file": f8,
                 "section": s8, "addr": a})
    pcs, ef, es, place, count, stride = event_place(bid)
    eb, eblob = (0, elf.img) if ef == "BOOT.BIN" else srcs[(ef, es)]
    n_files = 1 + max(eblob[place - eb + stride * i + 3] for i in range(count))
    rows.append({"build": bid, "rule": "pairs", "pc": pcs + count * stride, "pc_end": pcs + count * stride + 4 * n_files,
                 "file": ef, "section": es, "addr": place + count * stride})
    lo = hv["pc"] + 2 * hv["count"]                       # the records after the s16 table
    import exe_tables
    targets = sorted({int(t, 16) for a_, k, t in exe_tables.load_layout() if lo <= a_ < lo + 0x100 and k == "data"})
    targets = [t for t in targets if t > lo]          # the records' own words end where the first table starts
    first, last = targets[0], targets[-1]
    span = min(b - a_ for a_, b in zip(targets, targets[1:]) if b - a_ >= 0x10)   # a table's length
    h = hole_segments(bid, first)
    if h:
        f, s, addr, _ = h
        rows.append({"build": bid, "rule": "holes", "pc": first, "pc_end": last + span, "file": f, "section": s,
                     "addr": addr})
    w = wheel_place(elf, pc) if psp else wheel_place_psx(srcs, pc)
    if w:
        rows.append({"build": bid, "rule": "widen%d" % w[5], "pc": w[0], "pc_end": w[1], "file": w[3],
                     "section": w[4], "addr": w[2]})
    for tlo, thi, tfile, _, *extra in TWINS:
        only = extra[0] if extra else None
        nth = extra[1] if len(extra) > 1 else 0
        if only and bid not in only:
            continue
        t = twin_place(srcs, pc, tlo, thi, tfile, nth)
        if t:
            rows.append({"build": bid, "rule": "twin", "pc": tlo, "pc_end": thi, "file": tfile, "section": t[0],
                         "addr": t[1]})
        else:
            print("  %s twin 0x%06X..0x%06X: not in %s" % (bid, tlo, thi, tfile))
    rows += link_rows(bid, srcs, pc)
    wm = wmrec_place(srcs, pc)
    if wm:
        rows.append({"build": bid, "rule": "wmrec", "pc": WM_RECORDS, "pc_end": WM_RECORDS + WM_COUNT * WM_STRIDE,
                     "file": wm[0], "section": wm[1], "addr": wm[2]})
    else:
        print("  %s wmrec: the world maps' record table not found in ETC/GAME.EMI" % bid)
    if psp:
        ch = records_place(srcs, pc, "ETC/GAME.EMI", CH_RECORDS, CH_COUNT, CH_STRIDE, CH_AREA)
        if ch:
            rows.append({"build": bid, "rule": "cellhk", "pc": CH_RECORDS,
                         "pc_end": CH_RECORDS + CH_COUNT * CH_STRIDE, "file": ch[0], "section": ch[1], "addr": ch[2]})
        else:
            print("  %s cellhk: the cell hooks' record table not found in ETC/GAME.EMI" % bid)
        b = boxxy_place(elf, pc)
        if b is not None:
            rows.append({"build": bid, "rule": "boxxy", "pc": BOX_XY, "pc_end": BOX_XY + BOX_TABLES * BOX_PC_STRIDE,
                         "file": "BOOT.BIN", "section": None, "addr": b})
        else:
            print("  %s boxxy: the dialogue box tables not found in BOOT.BIN" % bid)
        m = msets_place(elf)
        sets = music_sets_layout()
        if m is not None:
            rows.append({"build": bid, "rule": "msets", "pc": min(l for _, l in sets), "pc_end": sets[-1][0] + 8,
                         "file": "BOOT.BIN", "section": None, "addr": m})
        else:
            print("  %s msets: no single run of %d records in BOOT.BIN" % (bid, len(sets)))
    rows.sort(key=lambda r: r["pc"])
    kept = []
    for r in rows:
        lo_, raw, mask = build_fill(r, disc, elf, rule, srcs)
        bad = [i for i in range(len(raw)) if mask[i] and raw[i] != pc[lo_ + i - DATA_LO]]
        r["filled"] = sum(mask)
        print("  %s %-6s 0x%06X..0x%06X from %s%s 0x%X: %d bytes, %d not BOF3.exe's" % (
            bid, r["rule"], r["pc"], r["pc_end"], r["file"], "" if r["section"] is None else "#%d" % r["section"],
            r["addr"], r["filled"], len(bad)))
        if not bad:
            kept.append(r)
    if not psp:
        return kept
    taken = {x for r in kept for x in range(r["pc"], r["pc_end"])}
    psx = psxmap_rows(disc, bid, pc, srcs, taken)
    print("  %s psxmap: %d runs, %d bytes (%d of them non-zero on the PC) from the PSP's own files at %s's places" % (
        bid, len(psx), sum(r["filled"] for r in psx),
        sum(1 for r in psx for x in range(r["pc"], r["pc_end"]) if pc[x - DATA_LO]), PSX_MAP))
    rows = kept + psx
    u = unwide_row(bid, pc)
    if u:
        rows.append(u)
    return sorted(rows, key=lambda r: r["pc"])


def unwide_bytes(img, owner):
    """UNWIDE applied to an image's placed bytes: [(pc, 2 bytes)], or None when a word
    is not placed."""
    out = []
    for a in UNWIDE:
        if owner[a - DATA_LO] is None or owner[a + 1 - DATA_LO] is None:
            return None
        x, = struct.unpack_from("<h", img, a - DATA_LO)
        out.append((a, struct.pack("<h", x + 32 if x < 160 else x - 32)))
    return out


def unwide_row(bid, pc):
    """The unwide row for a PSP build, written only when the rule gives BOF3.exe's bytes
    from the image the other rules build (psxmap_rows keeps it)."""
    img, owner = _BASE_IMAGE[bid]
    got = unwide_bytes(img, owner)
    if got is None or any(raw != pc[a - DATA_LO:a - DATA_LO + 2] for a, raw in got):
        print("  %s unwide: not BOF3.exe's, no row" % bid)
        return None
    print("  %s unwide: %d side placements back to the 4:3 frame, 0 not BOF3.exe's" % (bid, len(got)))
    return {"build": bid, "rule": "unwide", "pc": UNWIDE[0], "pc_end": UNWIDE[-1] + 2, "file": "-",
            "section": None, "addr": 0, "filled": 2 * len(got)}


def unwide(bid, img, owner, rows=None):
    """A PSP build's image: the PSP's 16:9 re-framing undone (UNWIDE), when the recipe has
    the build's unwide row. [(pc, bytes, where, address)] for exe_tables.disc_image."""
    rows = load_recipe()[bid] if rows is None else rows
    if _RECIPE_BASE or not any(r["rule"] == "unwide" for r in rows):
        return []
    got = unwide_bytes(img, owner)
    if got is None:
        fail("%s: the message box's side placements are not placed; the unwide row does not apply" % bid)
    return [(a, raw, "unwide", 0) for a, raw in got]


def psxmap_rows(disc, bid, pc, srcs, taken):
    """What the PSP build's image leaves unfilled that PSX_MAP's segments (exe_maps,
    exe-places.tsv) place from a file the PSP disc also has: each unfilled run of such
    a segment - not an engine-own byte, not a language range of exe-gaps.tsv, not a
    rule's - read from the PSP's file at the same address, kept only when the whole
    run equals BOF3.exe's and holds a non-zero byte."""
    import exe_tables
    import tables
    import psp_exe as imported      # exe_tables' copy (this file may be running as __main__)
    imported._RECIPE_BASE = True
    try:
        img, owner, _, _, _ = exe_tables.disc_built(disc, bid, exe_tables.load_pointers(),
                                                    exe_tables.load_rebuild_refused()[bid])
    finally:
        imported._RECIPE_BASE = False
    _BASE_IMAGE[bid] = (img, owner)
    skip = set(taken) | exe_tables.own_bytes()
    gaps, _ = exe_tables.load_gaps()
    skip.update(x for lo, hi, how, _, _ in gaps.get(bid, []) if how == "language" for x in range(lo, hi))
    segs = tables.read_map(os.path.join(tables.MAPS, PSX_MAP + ".tsv")) + exe_tables.load_places().get(PSX_MAP, [])
    out = []
    for s in sorted(segs, key=lambda r: r["pc"]):
        if (s["file"], s["section"]) not in srcs:
            continue
        base, blob = srcs[(s["file"], s["section"])]
        x = s["pc"]
        while x < s["pc_end"]:
            if owner[x - DATA_LO] is not None or x in skip:
                x += 1
                continue
            y = x
            while y < s["pc_end"] and owner[y - DATA_LO] is None and y not in skip:
                y += 1
            at = s["addr"] + x - s["pc"] - base
            if blob[at:at + y - x] == pc[x - DATA_LO:y - DATA_LO] and any(pc[x - DATA_LO:y - DATA_LO]):
                out.append({"build": bid, "rule": "psxmap", "pc": x, "pc_end": y, "file": s["file"],
                            "section": s["section"], "addr": s["addr"] + x - s["pc"], "filled": y - x})
            x = y
    return out


def wheel_place(elf, pc):
    """The formation wheel's disc twin in BOOT.BIN: the PC's ten 28-byte entries (a
    16-byte name, three s16 spots) as 20-byte entries (an 8-byte name), found by the
    spots (BOF3.exe's, at recipe time only); the lowest of the copies, which must all
    be equal. (pc, pc_end, address) or None."""
    sym = data_symbol("Equip_SlotIcons")
    lo = sym["pc"] + 0x50
    n = 10
    spots = [pc[lo + 28 * i + 16 - DATA_LO:lo + 28 * i + 28 - DATA_LO] for i in range(n)]
    dlo, dhi = elf.span(".data")
    hits = []
    a = elf.img.find(spots[0], dlo, dhi)
    while a >= 0:
        if all(elf.img[a + 20 * i:a + 20 * i + 12] == spots[i] for i in range(n)):
            hits.append(a - 8)
        a = elf.img.find(spots[0], a + 1, dhi)
    if not hits:
        return None
    if len({elf.img[h:h + 20 * n] for h in hits}) != 1:
        fail("BOOT.BIN's copies of the formation wheel differ")
    return lo, lo + 28 * n, hits[0], "BOOT.BIN", None, 8


def wheel_place_psx(srcs, pc):
    """The formation wheel on a PSX disc: as wheel_place, in the EMIs (each menu
    overlay carries a copy, found by BOF3.exe's spots at recipe time); the first in
    path order, all copies' spots equal. (pc, pc_end, address, file, section) or None."""
    sym = data_symbol("Equip_SlotIcons")
    lo = sym["pc"] + 0x50
    n = 10
    spots = [pc[lo + 28 * i + 16 - DATA_LO:lo + 28 * i + 28 - DATA_LO] for i in range(n)]
    hits = []
    for (f, s), (base, blob) in sorted(srcs.items(), key=lambda kv: (kv[0][0], kv[0][1] or 0)):
        a = blob.find(spots[0])
        while a >= 0:
            for k in (8, 10, 12):                         # the disc's name width (the stride less the spots)
                if a >= k and all(blob[a + (k + 12) * i:a + (k + 12) * i + 12] == spots[i] for i in range(n)):
                    hits.append((f, s, base + a - k, k))
            a = blob.find(spots[0], a + 1)
    if not hits:
        return None
    f, s, addr, k = hits[0]
    return lo, lo + 28 * n, addr, f, s, k


@functools.lru_cache(None)
def music_sets_layout():
    """[(record address, its list's address)] for Area_ZoneTrack's records: the layout's
    data pointer words at MUSIC_SETS + 8 i, as long as they run (recipes/exe-layout.tsv)."""
    import exe_tables
    words = {a: int(t, 16) for a, k, t in exe_tables.load_layout() if k == "data"}
    out, a = [], MUSIC_SETS
    while a in words:
        out.append((a, words[a]))
        a += 8
    if not out:
        fail("exe-layout.tsv has no pointer word at the music sets 0x%X" % MUSIC_SETS)
    return out


def msets_place(elf):
    """BOOT.BIN's music-set records, by its relocations: the one run in .data of as many
    8-byte records as the PC's whose +0 word is relocated and points before the run,
    rising, and whose +4 word is a count 1..255 that fits before the next list. The
    address or None."""
    n = len(music_sets_layout())
    dlo, dhi = elf.span(".data")
    dp = elf.data_pointers
    hits = []
    for a in range(dlo, dhi - 8 * n, 4):
        if not all(a + 8 * i in dp for i in range(n)):
            continue
        rec = [struct.unpack_from("<II", elf.img, a + 8 * i) for i in range(n)]
        if all(1 <= c < 0x100 for _, c in rec) and all(dlo <= p < a for p, _ in rec) \
                and all(rec[i][0] + 3 * rec[i][1] <= rec[i + 1][0] for i in range(n - 1)) \
                and rec[-1][0] + 3 * rec[-1][1] <= a:
            hits.append(a)
    if len(hits) != 1:
        return None
    return hits[0]


def boxxy_place(elf, pc):
    """BOOT.BIN's dialogue box tables: the one place in .data where both tables' entries
    0..2 are the PC's pairs as s16, 0x1C apart. The address or None."""
    keys = [b"".join(struct.pack("<hh", pc[BOX_XY + BOX_PC_STRIDE * t + 2 * e - DATA_LO],
                                 pc[BOX_XY + BOX_PC_STRIDE * t + 2 * e + 1 - DATA_LO]) for e in range(3))
            for t in range(BOX_TABLES)]
    dlo, dhi = elf.span(".data")
    hits = []
    a = elf.img.find(keys[0], dlo, dhi)
    while a >= 0:
        if elf.img[a + BOX_PSP_STRIDE:a + BOX_PSP_STRIDE + len(keys[1])] == keys[1]:
            hits.append(a)
        a = elf.img.find(keys[0], a + 1, dhi)
    return hits[0] if len(hits) == 1 else None


AREA_COUNT, LINK_PTR, LINK_LAST, LINK_SIZE = 200, 0x20, 0x30, 12


def link_rows(bid, srcs, pc):
    """`twin` rows for the areas' link lists (Area_LinkAt, area_entry.cpp: the descriptor's
    +0x20 list of 12-byte records, +0x30 the last index), each the first copy of the PC's
    list in the area's own overlay AREAnnn.EMI. The descriptors, pointers and counts are
    BOF3.exe's addresses and counts; the bytes are the disc's. Only lists the disc carries."""
    def word(a):
        return struct.unpack_from("<I", pc, a - DATA_LO)[0]
    files = {}
    for f, _s in srcs:
        m = re.search(r"AREA(\d{3})\.EMI$", f)
        if m:
            files.setdefault(int(m.group(1)), f)
    out = []
    descriptors = data_symbol("Area_Descriptors")["pc"]
    for area in range(AREA_COUNT):
        d = word(descriptors + 4 * area)
        if not DATA_LO <= d < DATA_HI or area not in files:
            continue
        lp = word(d + LINK_PTR)
        n = pc[d + LINK_LAST - DATA_LO] + 1
        if not DATA_LO <= lp < DATA_HI or lp + LINK_SIZE * n > DATA_HI:
            continue
        t = twin_place(srcs, pc, lp, lp + LINK_SIZE * n, files[area])
        if t:
            out.append({"build": bid, "rule": "twin", "pc": lp, "pc_end": lp + LINK_SIZE * n, "file": files[area],
                        "section": t[0], "addr": t[1]})
    return out


def wmrec_place(srcs, pc):
    """The disc's world-map record table in ETC/GAME.EMI: the place whose eleven 0x1C-byte
    records hold BOF3.exe's area words at +0x18 (found by them, at recipe time). (file,
    section, address of record 0) or None."""
    return records_place(srcs, pc, "ETC/GAME.EMI", WM_RECORDS, WM_COUNT, WM_STRIDE, WM_AREA)


def records_place(srcs, pc, file, records, count, stride, field):
    """The disc's copy of a PC record table in `file`: the first place whose `count`
    records of `stride` bytes hold BOF3.exe's 4-byte words at +`field` (wmrec, cellhk).
    (file, section, address of record 0) or None."""
    want = [pc[records + stride * i + field - DATA_LO:records + stride * i + field + 4 - DATA_LO]
            for i in range(count)]
    for (f, s), (base, blob) in sorted(srcs.items(), key=lambda kv: (kv[0][0], kv[0][1] or 0)):
        if f != file:
            continue
        a = blob.find(want[0])
        while a >= 0:
            if all(blob[a + stride * i:a + stride * i + 4] == want[i] for i in range(count)):
                return f, s, base + a - field
            a = blob.find(want[0], a + 1)
    return None


def twin_place(srcs, pc, lo, hi, file, nth=0):
    """The nth (0: the first) copy of BOF3.exe's [lo, hi) in `file`'s sections, in
    section and address order: (section, disc address) or None."""
    nd = pc[lo - DATA_LO:hi - DATA_LO]
    for (f, s), (base, blob) in sorted(srcs.items(), key=lambda kv: (kv[0][0], kv[0][1] or 0)):
        if f == file:
            at = blob.find(nd)
            while at >= 0:
                if nth == 0:
                    return s, base + at
                nth -= 1
                at = blob.find(nd, at + 1)
    return None


def write_recipe(rows):
    lines = ["# recipes/exe-psp.tsv - GENERATED by `tools/psp_exe.py recipe`; do not edit.",
             "# The game values a disc carries in another shape than BOF3.exe's (docs/psp-image.md,",
             "# docs/disc-gap-fills.md): per disc build (PSX and PSP), the PC range [pc, pc_end) a rule fills",
             "# from `file` (BOOT.BIN or an EMI and its section) at `addr` - rows8 (Magic_Rows' file ids),",
             "# pairs (EventBattle_Records' file array), holes (Effect_HpDamageVariance's set-file tables),",
             "# widen<k> (the formation wheel's spots, the disc's name k bytes), psxmap (a PSP disc's own EMI",
             "# at the PSX-JP map's place), twin (a short run verbatim in its reader's overlay, psp_exe.TWINS),",
             "# msets (the zone music sets from BOOT.BIN's packed lists) - and how many bytes it fills.",
             "# A row is written only when every",
             "# byte equals BOF3.exe's.",
             "# Addresses and counts only (CLAUDE.md rule 1).",
             "\t".join(COLS)]
    for r in rows:
        lines.append("%s\t%s\t0x%06X\t0x%06X\t%s\t%s\t0x%08X\t%d" % (
            r["build"], r["rule"], r["pc"], r["pc_end"], r["file"], "-" if r["section"] is None else r["section"],
            r["addr"], r["filled"]))
    with open(RECIPE, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


