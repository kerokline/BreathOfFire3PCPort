#!/usr/bin/env python
"""The PSP's image of BOF3.exe's .data, and the game values a PSP disc carries (docs/psp-image.md).

A disc-built image of .data (tools/exe_tables.py, docs/exe-import-engine.md) leaves
zero what no disc carries *verbatim* (recipes/exe-gaps.tsv). Four of the largest such
gaps are on a PSP disc in another shape, and this module fills them for a PSP-built
image:

    rows8    Magic_Rows' u16 effect file beside each row's code pointer: BOOT.BIN holds
             the table row for row (found by its relocations: the one run in .data of
             as many stride-8 rows as the PC's whose +4 word is relocated into .text and
             whose +0 word is not), in the disc's file numbering
    pairs    EventBattle_Records+0xE0, the file half of each (file, track) pair: the u16
             file array that follows the record table in BOOT.BIN (the catalogued
             event_battles place, tables.toml, + its count x stride), one entry per index
             the records' byte +3 names; the track half is the port's (no disc has it)
    holes    Effect_HpDamageVariance's halfword tables (the dragon forms' set files): the
             bytes between two segments of exe_maps/<build>.tsv of one file at one
             displacement (BATTLE.EMI#15), in the disc's file numbering
    widen8   the formation wheel (Equip_SlotIcons+0x50): ten entries of an 8-byte name and
             three s16 (x, z) spots on the disc, a 16-byte name on the PC; the spots are
             copied, the names left to the language layer

The file numbering. A disc names a file by its index in the disc's file table; the PSP's
BOOT.BIN holds that table as 0x40-byte path records (found by the disc's own paths). The
PC names a DAT/ file by its index in Dat_FileNames (symbols.toml), whose words
recipes/exe-layout.tsv holds as addresses into the name pool src/hook/exe_own.cpp lays
from recipes/pc-zh.toml. So a disc id becomes a PC id by its path's stem: no number is
copied. A disc file the PC ships no DAT for keeps its directory's displacement into a
slot Dat_FileNames leaves null (exe-layout.tsv has no word there); anything else refuses.

recipes/exe-psp.tsv (generated by `recipe`, which needs BOF3.exe: a row is written only
when the filled bytes equal the PC's) holds each fill's place - addresses and counts
only. exe_tables.disc_image applies them to a PSP build's image (`fill`); exe_tables
`recipe` then records the image's hash as for any build.

    python tools/psp_exe.py recipe  --game DIR --disc PSP-JP --disc PSP-EU    # recipes/exe-psp.tsv
    python tools/psp_exe.py measure --game DIR --disc DISC [...] --out DIR    # the class-by-class comparison
    python tools/psp_exe.py beside  --game DIR --disc PSX --disc PSP           # what a PSP disc would fill in a
                                                                               # PSX-built image (report only)
    python tools/psp_exe.py check                                              # the recipe alone (CI)

Everything this tool writes outside recipes/ is derived from the player's files and goes
to a scratch or analysis/ directory (CLAUDE.md rule 1).
"""
