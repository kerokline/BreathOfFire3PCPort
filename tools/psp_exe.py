def build_fill(row, disc, elf, rule, srcs):
    """One recipe row's bytes: (pc, bytes, mask) - mask True where the byte is the
    rule's to write (False: left to whatever else fills it)."""
    rl, lo, hi = row["rule"], row["pc"], row["pc_end"]
    base, blob = (0, elf.img) if row["file"] == "BOOT.BIN" else srcs[(row["file"], row["section"])]
    at = row["addr"] - base
    out, mask = bytearray(hi - lo), [False] * (hi - lo)
    if rl == "rows8":
        for r in range((hi - lo) // 8):
            w0, w4 = struct.unpack_from("<II", blob, at + 8 * r)
            ok = ((at + 8 * r + 4) in elf.data_pointers and (at + 8 * r) not in elf.data_pointers) if elf else \
                (0x80010000 <= w4 < 0x80200000 and not 0x80000000 <= w0 < 0x80200000)
            if not ok:
                fail("%s: %s 0x%X row %d is no code-pointer row" % (row["build"], row["file"], row["addr"], r))
            f, x = struct.unpack_from("<HH", blob, at + 8 * r)
            struct.pack_into("<HH", out, 8 * r, map_ids(rule, f), x)
            mask[8 * r:8 * r + 4] = [True] * 4
    elif rl == "pairs":
        for i in range((hi - lo) // 4):
            f, = struct.unpack_from("<H", blob, at + 2 * i)
            struct.pack_into("<H", out, 4 * i, map_ids(rule, f))
            mask[4 * i:4 * i + 2] = [True] * 2
    elif rl == "holes":
        for i in range((hi - lo) // 2):
            v, = struct.unpack_from("<H", blob, at + 2 * i)
            struct.pack_into("<H", out, 2 * i, map_ids(rule, v, keep=(0,)))
            mask[2 * i:2 * i + 2] = [True] * 2
    elif rl.startswith("widen"):
        k = int(rl[5:])                                   # the disc's name width; its entry k + 12
        for i in range((hi - lo) // 28):
            out[28 * i + 16:28 * i + 28] = blob[at + (k + 12) * i + k:at + (k + 12) * i + k + 12]
            mask[28 * i + 16:28 * i + 28] = [True] * 12
    elif rl in ("psxmap", "pspmap", "twin"):
        out[:] = blob[at:at + hi - lo]
        mask = [True] * (hi - lo)
    elif rl == "boxxy":
        for t in range(BOX_TABLES):
            for e in range(BOX_ENTRIES):
                x, y = struct.unpack_from("<hh", blob, at + BOX_PSP_STRIDE * t + 4 * e)
                x += BOX_UNWIDE.get(e, 0)
                if not (0 <= x < 0x100 and 0 <= y < 0x100):
                    fail("%s: BOOT.BIN 0x%X box %d.%d is off the PC's u8 layout" % (row["build"], row["addr"], t, e))
                o = BOX_PC_STRIDE * t + 2 * e
                out[o], out[o + 1] = x, y
                mask[o:o + 2] = [True, True]
    elif rl == "wmrec":
        for i in range((hi - lo) // WM_STRIDE):
            o = WM_STRIDE * i + WM_AREA
            out[o:o + 4] = blob[at + o:at + o + 4]
            mask[o:o + 4] = [True] * 4
    elif rl == "cellhk":
        for i in range((hi - lo) // CH_STRIDE):
            o = CH_STRIDE * i + CH_AREA
            out[o:o + 4] = blob[at + o:at + o + 4]
            mask[o:o + 4] = [True] * 4
    elif rl == "faerie":
        for i in range(faerie_records(hi - lo)):
            o, d = FA_STRIDE * i + FA_FIELD, FA_DISC_STRIDE * i + FA_DISC_FIELD
            out[o:o + 4] = blob[at + d:at + d + 4]
            mask[o:o + 4] = [True] * 4
    elif rl == "verb":
        if hi - lo != 1 or lo != VERB_AT or blob[at] != VERB_WEST:
            fail("%s: %s 0x%X is not set 8's Western 23rd verb (0x%02X)" % (row["build"], row["file"], row["addr"], VERB_WEST))
        out[0], mask[0] = VERB_PORT, True
    elif rl == "msets":
        # A list is its entries and the bytes after them up to the next list (Area_ZoneTrack
        # reads the entry past the last as the fallback): the disc's span, as far as the
        # PC's room for it reaches.
        sets = music_sets_layout()
        recs = [struct.unpack_from("<II", blob, at + 8 * i) for i in range(len(sets))]
        disc_ends = [p for p, _ in recs[1:]] + [at]
        pc_ends = sorted({l for _, l in sets} | {sets[0][0]})
        for i, (rec, lst) in enumerate(sets):
            p, n = recs[i]
            room = min(e for e in pc_ends if e > lst) - lst
            span = min(disc_ends[i] - p, room)
            if not (lo <= lst and rec + 8 <= hi and n < 0x100 and 3 * n < span):
                fail("%s: BOOT.BIN 0x%X record %d does not fit the PC's music sets" % (row["build"], row["addr"], i))
            out[rec + 4 - lo:rec + 8 - lo] = struct.pack("<I", n)
            mask[rec + 4 - lo:rec + 8 - lo] = [True] * 4
            out[lst - lo:lst - lo + span] = blob[p:p + span]
            mask[lst - lo:lst - lo + span] = [True] * span
    else:
        fail("exe-psp.tsv: unknown rule %s" % rl)
    return lo, bytes(out), mask


def load_recipe(path=RECIPE):
    out = collections.defaultdict(list)
    if not os.path.exists(path):
        return out
    with open(path, encoding="utf-8") as f:
        lines = [l.rstrip("\n") for l in f if not l.startswith("#")]
    if not lines or lines[0].split("\t") != COLS:
        fail("exe-psp.tsv: the column line is not %s" % "\t".join(COLS))
    for l in lines[1:]:
        c = l.split("\t")
        out[c[0]].append({"build": c[0], "rule": c[1], "pc": int(c[2], 16), "pc_end": int(c[3], 16), "file": c[4],
                          "section": None if c[5] == "-" else int(c[5]), "addr": int(c[6], 16), "filled": int(c[7])})
    return out


def fill(disc, bid, owner, rows=None, srcs=None, ranges=None, img=None):
    """The PSP fills for a PSP build's image (exe_tables.disc_image's call): [(pc,
    bytes, where, disc address)] for the runs of each recipe row's bytes that nothing
    has filled yet. No row for another build. `srcs`: exe_twins.sources as
    {(file, section): (base, bytes)}, if the caller has it.

    `ranges` and `img` (disc_image's [pc, end, how, where, addr] and image so far):
    given, a `twin` row also takes back a byte a `map` segment of ANOTHER file
    placed with another value - a segment that ran past its own data into the
    structure the twin's own overlay holds (D267: BATTLE.EMI#15 over MAGIC226's
    lifts; D268: AREA111's over AREA112's link list). A twin's bytes are BOF3.exe's
    by construction (the recipe keeps no other); a byte that already equals the
    twin's, and every byte of a segment from the twin's own file, keep their
    owner, so no disc value is lost and nothing placed by those bytes moves
    (taking the equal bytes too moved 13 of the PSP's places, measured 2026-10-17)."""
    rows = load_recipe()[bid] if rows is None else rows
    if not rows or _RECIPE_BASE:
        return []
    elf = boot_bin(disc) if bid in PSP else None
    srcs = sources_of(disc) if srcs is None else srcs
    rule = id_rule(disc_ids(disc, bid, srcs, elf))
    out = []
    for row in rows:
        if row["rule"] == "unwide":
            continue                                  # applied after the fills (unwide)
        lo, raw, mask = build_fill(row, disc, elf, rule, srcs)
        where = "%s%s:%s" % (row["file"], "" if row["section"] is None else "#%d" % row["section"], row["rule"])

        def free(x):
            k = owner[x - DATA_LO]
            if k is None:
                return True
            if ranges is None or img is None or row["rule"] != "twin":
                return False
            r = ranges[k]
            return (r[2] == "map" and r[3].split("#")[0] != row["file"]
                    and img[x - DATA_LO] != raw[x - lo])
        i = 0
        while i < len(raw):
            if not mask[i] or not free(lo + i):
                i += 1
                continue
            j = i
            while j < len(raw) and mask[j] and free(lo + j):
                j += 1
            out.append((lo + i, raw[i:j], where, row["addr"]))
            i = j
    return out


