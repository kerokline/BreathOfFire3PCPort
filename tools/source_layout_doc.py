"""Write docs/source-layout.md: the reader of the source-layout round's unit table.

    python tools/source_layout_doc.py            # write docs/source-layout.md
    python tools/source_layout_doc.py --check    # fail if the committed doc is not what the tree gives

Reads analysis/tu_layout.tsv (tools/tu_census.py: each function, its unit, the
file of its unit, the confidence, the PlayStation unit it agrees with) and
analysis/tu_moves.tsv (tools/move_funcs.py and tools/retire_shells.py: the
seams, the files that moved whole) and the tree (the fuzz files, the flat
files). Our names and paths only; no byte of the game.
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "source-layout.md"
GAME = ROOT / "src" / "game"

FOLDERS = {
    "area": "the area overlays (the PlayStation's `AREAnnn.EMI`), one file an area or a world's shared code",
    "battle": "the battle engine",
    "boss": "the boss overlays",
    "community": "the faerie village",
    "core": "the game's frame, modes, title and load",
    "effect": "the effect kinds and the effect engine",
    "field": "the field: maps, objects, members, events",
    "magic": "the spell overlays",
    "menu": "the menus and their windows",
    "minigame": "the minigames",
    "platform": "the port's own layer: Direct3D, sound, the PlayStation library's stand-ins",
    "scenario": "the scenario chapters",
    "shop": "the shops and the camp",
    "text": "text drawing and the message box",
}


def rows(path: Path, skip_hash_header: bool = False):
    with open(path, encoding="utf-8", newline="") as f:
        lines = [l for l in f if not l.startswith("# ")]
    if lines and lines[0].startswith("#"):
        lines[0] = lines[0][1:]
    return list(csv.DictReader(lines, delimiter="\t"))


def build() -> str:
    layout = rows(ROOT / "analysis" / "tu_layout.tsv")
    moves = rows(ROOT / "analysis" / "tu_moves.tsv")
    files: dict[str, list[dict]] = defaultdict(list)
    for r in layout:
        if r["proposed_file"]:
            files[r["proposed_file"]].append(r)
    seams: dict[str, list[str]] = defaultdict(list)
    whole: list[tuple[str, str]] = []
    retired = 0
    for r in moves:
        if r["kind"] == "seam":
            seams[r["new_path"]].append(r["name"])
        elif r["kind"] == "file":
            whole.append((r["old_path"], r["new_path"]))
        elif r["kind"] == "shell":
            retired += 1
    remainders = sorted((n, o) for o, n in whole if not n.endswith("_fuzz.cpp"))
    fuzz = Counter(n.split("/")[2] for o, n in whole if n.endswith("_fuzz.cpp"))
    flat = sorted(p.name for p in GAME.glob("*.cpp"))
    flat_h = len(list(GAME.glob("*.h")))

    L: list[str] = []
    L.append("# The source layout: Capcom's translation units as our files")
    L.append("")
    L.append("**Status:** GENERATED by `tools/source_layout_doc.py` from `analysis/tu_layout.tsv`, "
             "`analysis/tu_moves.tsv` and the tree; do not edit by hand. The method, the evidence and the "
             "owner's calls are in [`source-layout-round.md`](source-layout-round.md).")
    L.append("")
    L.append("Every function of Capcom's that is ours lives in the file of the translation unit it was "
             "compiled in, as far as the binary and the PlayStation overlays let it be recovered. A unit "
             "is a run of `.text` (`unit_lo..unit_hi`); a file holds one unit or several that the round "
             "joined. The confidence of a function's place is `joined` (a PlayStation order run or a "
             "unit-local static says so), `placed` (data order, a local code-pointer table, or its only "
             "callers), or `guessed` (our names or one call).")
    L.append("")
    total = sum(len(v) for f, v in files.items() if f.count("/") == 3)
    outside = sum(len(v) for f, v in files.items() if f.count("/") != 3)
    by_folder: dict[str, list[str]] = defaultdict(list)
    for f in files:
        parts = f.split("/")
        by_folder[parts[2] if len(parts) == 4 else "(flat)"].append(f)
    L.append("## 1. The tree")
    L.append("")
    L.append(f"{total:,} functions in {sum(len(v) for k, v in by_folder.items() if k != '(flat)'):,} unit "
             f"files under {len([k for k in by_folder if k != '(flat)'])} folders of `src/game/`"
             + (f" (and the runtime's {outside}, outside the round, in `src/game/crt_rest.cpp`)." if outside else "."))
    L.append("")
    L.append("| Folder | What it holds | Unit files | Functions | Fuzz files | Files of ours |")
    L.append("|---|---|---:|---:|---:|---:|")
    ours_by = Counter(n.split("/")[2] for n, _ in remainders)
    for folder in sorted(k for k in by_folder if k != "(flat)"):
        fs = by_folder[folder]
        L.append(f"| `{folder}/` | {FOLDERS.get(folder, '')} | {len(fs)} | {sum(len(files[f]) for f in fs):,} "
                 f"| {fuzz.get(folder, 0)} | {ours_by.get(folder, 0)} |")
    L.append("")
    L.append("Beside the unit files a folder holds:")
    L.append("")
    L.append("- **the fuzz files** (`<group>_fuzz.cpp`): the start-up differential fuzz of one takeover "
             "group, named after the group, in the folder most of the group's functions went to. A group's "
             "`SelfTest()` is called from `src/hook/inject_all.cpp`, before the group's functions are bound;")
    L.append("- **files of ours** (section 3): what a takeover group's file still held that is not "
             "Capcom's - a divergence's switch and its arming, a self-test written in the file, a module "
             "of ours - moved whole in stage C and to be dissolved in the cleanup round.")
    L.append("")
    L.append(f"**Flat in `src/game/`:** {len(flat)} sources - the harness files shared by many groups and "
             f"the runtime's file, whose range is outside the round ({', '.join('`' + n + '`' for n in flat)}) - "
             f"and {flat_h} headers: the shared ones (`records.h`, `record_views.h`, `move_script_bytes.h`, "
             "the harness headers, `widescreen.h`), each group's `<group>_callees.h` (its callee constants "
             "and seam, stage E's to retire) and the headers of the files of ours. An include is always "
             "`game/<name>.h` or `game/<folder>/<name>.h`.")
    L.append("")
    L.append("**Where a new function goes.** A function of Capcom's taken over later goes into the file of "
             "its unit: its row in `analysis/tu_layout.tsv` names it (`tools/tu_census.py --check --strict` "
             "fails otherwise). Code of ours that is not Capcom's goes beside the unit it serves, in that "
             "folder, in a file of its own or in the unit's file; never flat in `src/game/` "
             "(`tools/retire_shells.py --check --strict`). `tools/cite_lookup.py` answers a path written "
             "before the round.")
    L.append("")
    L.append("## 2. The unit files")
    L.append("")
    L.append("One row a file: its `.text` range (the lowest unit's start to the highest unit's end), the "
             "units in it, its functions by confidence (joined / placed / guessed), the PlayStation unit "
             "most of them agree with, and the callee seams that live in it.")
    for folder in sorted(k for k in by_folder if k != "(flat)"):
        L.append("")
        L.append(f"### `{folder}/`")
        L.append("")
        L.append("| File | Range | Units | Functions (j / p / g) | PlayStation unit | Seams |")
        L.append("|---|---|---:|---|---|---|")

        def lo(f):
            return min(int(r["unit_lo"], 16) for r in files[f])

        for f in sorted(by_folder[folder], key=lo):
            rs = files[f]
            c = Counter(r["confidence"] for r in rs)
            psx = Counter(r["psx_unit_agreement"].split(":")[0].split("#")[0] for r in rs if r["psx_unit_agreement"])
            top = psx.most_common(1)
            twin = f"{top[0][0]} ({top[0][1]})" if top else ""
            hi = max(int(r["unit_hi"], 16) for r in rs)
            L.append(f"| `{f.split('/')[-1]}` | `0x{lo(f):X}..0x{hi:X}` | {len({r['unit'] for r in rs})} "
                     f"| {len(rs)} ({c.get('joined', 0)} / {c.get('placed', 0)} / {c.get('guessed', 0)}) "
                     f"| {twin} | {', '.join('`' + s + '`' for s in sorted(seams.get(f, [])))} |")
    L.append("")
    L.append("## 3. The files of ours")
    L.append("")
    L.append(f"{len(remainders)} files moved whole in stage C, unchanged inside ({retired} pure shells were "
             "retired beside them). Each still carries its old group's name; one that met a unit file's "
             "name is `<group>_ours.cpp`. Its header stays flat.")
    L.append("")
    L.append("| File | Was |")
    L.append("|---|---|")
    for n, o in remainders:
        L.append(f"| `{n[len('src/game/'):]}` | `{o}` |")
    L.append("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        have = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if have != text:
            print("source_layout_doc --check: docs/source-layout.md is not what the tree gives (rerun the tool)")
            return 1
        print("source_layout_doc --check: docs/source-layout.md is current")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        eol = "\r\n" if b"\r\n" in (ROOT / "symbols.toml").read_bytes()[:65536] else "\n"
        f.write(text.replace("\n", eol))
    print(f"wrote docs/source-layout.md: {len(text.splitlines())} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
