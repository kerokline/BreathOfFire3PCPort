#!/usr/bin/env python
"""Print the story-flag numbers held in tables of the player's BOF3.exe.

    python tools/flag_tables.py --exe bof3/BOF3.exe
    python tools/flag_tables.py --exe bof3/BOF3.exe --markdown OUT.md

Some code takes a flag number from a table in the executable instead of naming it
(docs/story-flags.md, docs/story-flags/flag-tables.md). This repo does not quote
those values: recipes/flag-tables.tsv holds each table's layout only, and this
tool reads the values from the player's own copy when they are wanted.

--markdown writes the values as a page. That page quotes game data, so it must
not be written inside this repo (CLAUDE.md rule 1): the tool refuses a path
under the repo.
"""
import argparse
import hashlib
import os
import struct
import sys

REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
RECIPE = os.path.join(REPO, 'recipes', 'flag-tables.tsv')
COLS = ['name', 'address', 'count', 'stride', 'offset', 'width', 'kind', 'bank', 'adjust', 'used_by', 'confidence', 'note']


def die(msg):
    sys.exit('flag_tables: ' + msg)


class Exe:
    def __init__(self, path):
        self.data = open(path, 'rb').read()
        d = self.data
        if d[:2] != b'MZ':
            die('%s is not a PE file' % path)
        pe = struct.unpack_from('<I', d, 0x3C)[0]
        nsec = struct.unpack_from('<H', d, pe + 6)[0]
        opt = struct.unpack_from('<H', d, pe + 20)[0]
        self.base = struct.unpack_from('<I', d, pe + 52)[0]
        self.secs = [struct.unpack_from('<IIII', d, pe + 24 + opt + 40 * i + 8) for i in range(nsec)]

    def read(self, va, n):
        for _vs, v, rs, ro in self.secs:
            if self.base + v <= va and va + n <= self.base + v + rs:
                o = ro + va - self.base - v
                return self.data[o:o + n]
        return None


def recipe():
    if not os.path.exists(RECIPE):
        die('no recipe at %s' % RECIPE)
    rows = []
    for n, line in enumerate(open(RECIPE, encoding='utf8'), 1):
        line = line.rstrip('\n')
        if not line or line.startswith('#'):
            continue
        c = line.split('\t')
        if c[0] == 'name':
            continue
        if len(c) != len(COLS):
            die('recipe line %d has %d columns, not %d' % (n, len(c), len(COLS)))
        rows.append(dict(zip(COLS, c)))
    return rows


def num(s):
    try:
        return int(s, 0)
    except ValueError:
        return None


def values(exe, r):
    """(text, None) or (None, why) for one recipe line."""
    addr, count, stride, off = num(r['address']), num(r['count']), num(r['stride']), num(r['offset'])
    width = num(r['width']) or 1
    if None in (addr, count, stride, off):
        return None, 'layout not known (%s)' % r['confidence']
    raw = exe.read(addr, count * stride)
    if raw is None:
        return None, 'address not in the initialised image'
    kind = r['kind']
    if kind == 'bits':
        bits = [i * 8 + k for i in range(len(raw)) for k in range(8) if raw[i] >> k & 1]
        return 'flags set: ' + (' '.join(map(str, bits)) or 'none'), None
    adj = num(r['adjust']) if r['adjust'].strip() not in ('', '+0') else 0
    out = []
    for i in range(count):
        v = int.from_bytes(raw[i * stride + off:i * stride + off + width], 'little')
        if kind == 'cond':
            out.append('0x%0*X' % (width * 2, v))
        elif adj is None:
            out.append('%d (%s)' % (v, r['adjust']))
        elif width == 1 and v == 0xFF:
            out.append('-')
        else:
            out.append(str(v + adj))
    return ' '.join(out), None


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--exe', required=True, help="the player's BOF3.exe")
    ap.add_argument('--markdown', help='write a page of the values to this path, outside the repo')
    a = ap.parse_args()
    exe = Exe(a.exe)
    rows = recipe()
    sha = hashlib.sha256(exe.data).hexdigest()
    lines = []
    for r in rows:
        text, why = values(exe, r)
        lines.append((r, text if text is not None else '(not read: %s)' % why))
    if not a.markdown:
        print('BOF3.exe sha256 %s' % sha)
        for r, text in lines:
            print('%-28s %s  %-10s %-9s %s' % (r['name'], r['address'], r['bank'], r['confidence'], text))
            print('%-28s   %s' % ('', r['note']))
        return
    out = os.path.normpath(os.path.abspath(a.markdown))
    if os.path.commonpath([out, REPO]) == REPO:
        die('%s is inside this repo: the page quotes game data, write it somewhere else' % out)
    md = ['# Breath of Fire III (PC): flag numbers held in tables of the executable', '',
          'Generated by `tools/flag_tables.py` of BreathOfFire3PCPort from one copy of `BOF3.exe`',
          '(sha256 `%s`). Each row is a table the game reads a story-flag number from.' % sha, '',
          '- **Bank** says which flags the numbers index: `event` is the event-flag bank (save block',
          '  `+0x650`, PSX save file `+0x850`), `chapter N` is that chapter\'s 8-byte row (save block',
          '  `+0x5B0 + 8N`), `current` is the row of whichever chapter is running.',
          '- Flag `n` is bit `n & 7` of byte `n >> 3` of its bank.',
          '- `-` is an empty entry. A `cond` value is a condition code: its low byte is the flag number.',
          '- **Confidence** is how sure the layout is: `read` from the code, or `likely`.', '',
          '| Table | Address | Bank | Values | What the entries are | Confidence |', '|---|---|---|---|---|---|']
    for r, text in lines:
        md.append('| %s | `%s` | %s | %s | %s | %s |' % (r['name'], r['address'], r['bank'], text, r['note'], r['confidence']))
    with open(out, 'w', encoding='utf8', newline='\n') as f:
        f.write('\n'.join(md) + '\n')
    print('wrote %s (%d tables)' % (out, len(lines)))


if __name__ == '__main__':
    main()
